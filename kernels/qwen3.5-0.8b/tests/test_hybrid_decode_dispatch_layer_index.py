"""DAG-50: kernels/qwen3.5-0.8b/tests/test_hybrid_decode_dispatch_layer_index.py

Drift-guard for the Metal dispatch include
``iso/hybrid_decode_dispatch.inc`` against the arch.yaml source of truth.

This test file specifically guards the *layer-index* surface of the
dispatch include:

  * ``kHybridFullAttnInterval``         — every-Nth-layer cadence
  * ``kHybridFullAttnNumLayers``        — explicit full-layer count
  * ``kHybridFullAttnLayerIndices[]``   — explicit ascending index list
  * ``hybrid_layer_is_full`` / ``hybrid_layer_is_linear`` predicates
  * ``kArchSimdgroupSize``              — runtime simdgroup size binding

All assertions are pure-Python text parsing (regex against the .inc's
literal source). No Metal toolchain, no MSL compiler, no subprocess
spawning. The tests load arch.yaml with ``yaml.safe_load`` and skip
cleanly when ``pyyaml`` is unavailable or the file lacks the expected
key.

The dispatch include is auto-generated by ``python/codegen.py`` (see
commit ``544ace3`` for the regeneration that landed the ``kHybrid*``
prefix). If arch.yaml's ``full_attention`` block changes without
re-running codegen, these tests will fail with a concrete drift
message naming both sides.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

KERNELS = Path(__file__).resolve().parents[1]
ARCH_YAML = KERNELS / "arch.yaml"
DISPATCH_INC = KERNELS / "iso" / "hybrid_decode_dispatch.inc"

# Regexes — must tolerate the leading whitespace optional in MSL,
# the optional trailing comment, and the mandatory ``u`` literal.
#
# kHybridFullAttnInterval is a uint constant; we accept either
# ``= 4u;`` or ``= 4u;  // arch.yaml: full_attention.full_attention_interval``.
KHYBRID_FULL_INTERVAL_RE = re.compile(
    r"constant\s+uint\s+kHybridFullAttnInterval\s*=\s*(\d+)u\b"
)

# Num-layers scalar constant — same prefix style.  We accept either
# the legacy ``kHybridFullLayerCount`` name and the regenerated
# ``kHybridFullAttnNumLayers`` name so this test stays green across
# the rename wave (commit ``544ace3``).
KHYBRID_FULL_COUNT_RE = re.compile(
    r"constant\s+uint\s+(?:kHybridFullAttnNumLayers|kHybridFullLayerCount)"
    r"\s*=\s*(\d+)u\b"
)

# Array-literal of explicit full-attention indices.
# Pattern: ``constant uint kHybridFullAttnLayerIndices[N] = {3, 7, 11, 15, 19, 23};``
# We capture both the array size N and the literal list as a comma-joined string.
KHYBRID_FULL_INDICES_RE = re.compile(
    r"constant\s+uint\s+kHybridFullAttn(?:Attn)?LayerIndices\s*"
    r"\[\s*(?:kHybridFullAttnNumLayers|kHybridFullLayerCount|\d+)\s*\]"
    r"\s*=\s*\{([^}]+)\}\s*;"
)

# kArchSimdgroupSize — see also DAG-49 / DAG-53 — guard against a
# hard-coded ``32u`` in the simdgroup slot drifting away from
# arch.yaml's canonical value.
KARCH_SIMDGROUP_RE = re.compile(r"constant\s+uint\s+kArchSimdgroupSize\s*=\s*(\d+)u\b")

# QWEN3_5_NUM_HIDDEN_LAYERS reference — only present if the .inc
# derives a per-layer iteration guard.  We do not require it, but if
# present it must agree with arch.yaml.
QWEN_NUM_LAYERS_RE = re.compile(
    r"QWEN3_5_NUM_HIDDEN_LAYERS(?:_DEFAULT)?\s*(?:=|,)\s*(\d+)"
)


def _read_arch_yaml_full_attention() -> dict | None:
    """Parse ``full_attention`` block from arch.yaml, returning ``None``
    when ``pyyaml`` is missing or the file is unparseable. Callers must
    ``pytest.skip`` on ``None`` rather than failing hard."""
    if not ARCH_YAML.is_file():
        return None
    try:
        import yaml
    except ImportError:
        return None
    try:
        data = yaml.safe_load(ARCH_YAML.read_text())
    except (yaml.YAMLError, OSError):
        return None
    try:
        return dict(data["model"]["full_attention"])
    except (KeyError, TypeError):
        return None


def _read_arch_yaml_num_hidden_layers() -> int | None:
    """Parse ``model.num_hidden_layers`` from arch.yaml, or ``None``
    on missing-yaml / missing-key."""
    if not ARCH_YAML.is_file():
        return None
    try:
        import yaml
    except ImportError:
        return None
    try:
        data = yaml.safe_load(ARCH_YAML.read_text())
    except (yaml.YAMLError, OSError):
        return None
    try:
        return int(data["model"]["num_hidden_layers"])
    except (KeyError, TypeError, ValueError):
        return None


def _read_arch_yaml_simdgroup_size() -> int | None:
    """Parse ``kernel_strategy.default_simdgroup_size`` from arch.yaml."""
    if not ARCH_YAML.is_file():
        return None
    try:
        import yaml
    except ImportError:
        return None
    try:
        data = yaml.safe_load(ARCH_YAML.read_text())
    except (yaml.YAMLError, OSError):
        return None
    try:
        return int(data["kernel_strategy"]["default_simdgroup_size"])
    except (KeyError, TypeError, ValueError):
        return None


def _read_dispatch_inc() -> str | None:
    """Read the dispatch include's text, or ``None`` when missing."""
    if not DISPATCH_INC.is_file():
        return None
    try:
        return DISPATCH_INC.read_text()
    except OSError:
        return None


def _extract_inc_interval(text: str) -> int | None:
    m = KHYBRID_FULL_INTERVAL_RE.search(text)
    return int(m.group(1)) if m else None


def _extract_inc_count(text: str) -> int | None:
    m = KHYBRID_FULL_COUNT_RE.search(text)
    return int(m.group(1)) if m else None


def _extract_inc_indices(text: str) -> list[int] | None:
    m = KHYBRID_FULL_INDICES_RE.search(text)
    if not m:
        return None
    raw = m.group(1)
    out: list[int] = []
    for tok in raw.split(","):
        tok = tok.strip()
        if not tok:
            continue
        try:
            out.append(int(tok))
        except ValueError:
            return None
    return out


def _extract_inc_simdgroup_size(text: str) -> int | None:
    m = KARCH_SIMDGROUP_RE.search(text)
    return int(m.group(1)) if m else None


def test_dispatch_inc_uses_arch_yaml_interval() -> None:
    """The dispatch include's ``kHybridFullAttnInterval`` must equal
    ``arch.yaml.model.full_attention.full_attention_interval``. Drift here
    breaks the every-Nth-layer cadence predicate
    ``((layer + 1) % kHybridFullAttnInterval) == 0`` against the explicit
    ``kHybridFullAttnLayerIndices[]`` list."""
    arch_fa = _read_arch_yaml_full_attention()
    if arch_fa is None:
        pytest.skip(f"arch.yaml not parseable or pyyaml missing: {ARCH_YAML}")
    text = _read_dispatch_inc()
    if text is None:
        pytest.skip(f"dispatch include missing: {DISPATCH_INC}")
    arch_interval = int(arch_fa["full_attention_interval"])
    inc_interval = _extract_inc_interval(text)
    if inc_interval is None:
        pytest.skip(
            "kHybridFullAttnInterval not found in dispatch include "
            "(may have been renamed; update KHYBRID_FULL_INTERVAL_RE)"
        )
    assert inc_interval == arch_interval, (
        f"drift: arch.yaml.full_attention_interval={arch_interval} "
        f"vs dispatch inc kHybridFullAttnInterval={inc_interval}"
    )


def test_dispatch_inc_full_layer_count_matches_arch_yaml() -> None:
    """The dispatch include's full-attention layer count
    (``kHybridFullAttnNumLayers`` or legacy ``kHybridFullLayerCount``) must
    equal the count of items in ``arch.yaml.full_attention.full_attention_layer_indices``."""
    arch_fa = _read_arch_yaml_full_attention()
    if arch_fa is None:
        pytest.skip(f"arch.yaml not parseable or pyyaml missing: {ARCH_YAML}")
    text = _read_dispatch_inc()
    if text is None:
        pytest.skip(f"dispatch include missing: {DISPATCH_INC}")
    arch_indices = list(arch_fa["full_attention_layer_indices"])
    arch_count = len(arch_indices)
    inc_count = _extract_inc_count(text)
    if inc_count is None:
        pytest.skip(
            "kHybridFullAttnNumLayers/kHybridFullLayerCount not found "
            "in dispatch include (may have been renamed; update "
            "KHYBRID_FULL_COUNT_RE)"
        )
    assert inc_count == arch_count, (
        f"drift: arch.yaml full_attention_layer_indices | len = {arch_count} "
        f"vs dispatch inc full-layer count = {inc_count}"
    )


def test_dispatch_inc_full_layer_indices_match_arch_yaml() -> None:
    """The dispatch include's explicit ``kHybridFullAttnLayerIndices[]``
    list must match ``arch.yaml.full_attention.full_attention_layer_indices``
    exactly. The static_assert in the .inc assumes this equivalence."""
    arch_fa = _read_arch_yaml_full_attention()
    if arch_fa is None:
        pytest.skip(f"arch.yaml not parseable or pyyaml missing: {ARCH_YAML}")
    text = _read_dispatch_inc()
    if text is None:
        pytest.skip(f"dispatch include missing: {DISPATCH_INC}")
    arch_indices = [int(x) for x in arch_fa["full_attention_layer_indices"]]
    inc_indices = _extract_inc_indices(text)
    if inc_indices is None:
        pytest.skip(
            "kHybridFullAttnLayerIndices[...] = {...}; literal not found "
            "in dispatch include (may have been renamed; update "
            "KHYBRID_FULL_INDICES_RE)"
        )
    assert sorted(arch_indices) == sorted(inc_indices), (
        f"drift: arch.yaml full_attention_layer_indices={sorted(arch_indices)} "
        f"vs dispatch inc kHybridFullAttnLayerIndices={sorted(inc_indices)}"
    )
    # Strict order matters for the static_assert comment — both sides
    # are ascending in the current emit. If a future regen changes
    # sort order, this assertion will flag it explicitly.
    assert arch_indices == inc_indices, (
        f"order drift: arch.yaml={arch_indices} "
        f"vs dispatch inc={inc_indices} (lists must match in order)"
    )


def test_dispatch_inc_hybrid_decode_function_declared() -> None:
    """The dispatch include must export at least one decode entry point
    or per-layer kind predicate that a Metal shader can call. We accept
    the canonical ``hybrid_layer_is_full`` / ``hybrid_layer_is_linear``
    pair (current emit) or a future ``kHybridDecode(...)`` alias.

    This is a structural guard — the precise function name may evolve,
    but *some* decode-or-predicate surface must be present, otherwise
    the .inc is dead code that confuses the host engine module."""
    text = _read_dispatch_inc()
    if text is None:
        pytest.skip(f"dispatch include missing: {DISPATCH_INC}")
    canonical_predicates = (
        "hybrid_layer_is_full" in text and "hybrid_layer_is_linear" in text
    )
    shader_entry = bool(
        re.search(
            r"(?:kernel|vertex|fragment)\s+\w*[Dd]ecode\w*\s*\(",
            text,
        )
    )
    function_alias = "kHybridDecode" in text
    assert canonical_predicates or shader_entry or function_alias, (
        "dispatch include exposes no decode entry point: expected "
        "hybrid_layer_is_full + hybrid_layer_is_linear predicates, a "
        "kernel/vertex/fragment decode shader, or a kHybridDecode alias"
    )


def test_dispatch_inc_kArchSimdgroupSize_consistent() -> None:
    """``kArchSimdgroupSize`` in the dispatch include must equal
    ``arch.yaml.kernel_strategy.default_simdgroup_size``. This is the same
    invariant as the DAG-49 / DAG-53 drift-guards; we re-assert it here so
    a future regen that *only* updates the .inc (without re-touching
    arch.yaml) is caught at DAG-50 too."""
    arch_val = _read_arch_yaml_simdgroup_size()
    if arch_val is None:
        pytest.skip(f"arch.yaml not parseable or pyyaml missing: {ARCH_YAML}")
    text = _read_dispatch_inc()
    if text is None:
        pytest.skip(f"dispatch include missing: {DISPATCH_INC}")
    inc_val = _extract_inc_simdgroup_size(text)
    if inc_val is None:
        pytest.skip(
            "kArchSimdgroupSize not found in dispatch include "
            "(may have been renamed; update KARCH_SIMDGROUP_RE)"
        )
    assert inc_val == arch_val, (
        f"drift: arch.yaml.kernel_strategy.default_simdgroup_size={arch_val} "
        f"vs dispatch inc kArchSimdgroupSize={inc_val}"
    )


def test_dispatch_inc_num_hidden_layers_matches_arch_yaml() -> None:
    """Soft guard: if the dispatch include references
    ``QWEN3_5_NUM_HIDDEN_LAYERS`` (e.g. as a per-layer iteration bound
    for a downstream kernel), the referenced value must equal
    ``arch.yaml.model.num_hidden_layers``. If the .inc has no such
    reference, the test passes vacuously (skip-on-absent)."""
    arch_n = _read_arch_yaml_num_hidden_layers()
    if arch_n is None:
        pytest.skip(f"arch.yaml not parseable or pyyaml missing: {ARCH_YAML}")
    text = _read_dispatch_inc()
    if text is None:
        pytest.skip(f"dispatch include missing: {DISPATCH_INC}")
    m = QWEN_NUM_LAYERS_RE.search(text)
    if m is None:
        # Vacuous pass — the .inc does not currently emit a
        # ``QWEN3_5_NUM_HIDDEN_LAYERS`` reference. A future regen that
        # adds one will automatically be guarded.
        pytest.skip(
            "QWEN3_5_NUM_HIDDEN_LAYERS reference not present in "
            "dispatch include (vacuously consistent)"
        )
    inc_n = int(m.group(1))
    assert inc_n == arch_n, (
        f"drift: arch.yaml.model.num_hidden_layers={arch_n} "
        f"vs dispatch inc QWEN3_5_NUM_HIDDEN_LAYERS={inc_n}"
    )
