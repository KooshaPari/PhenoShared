def _build_arg_parser():
    """Build an argparse parser for the `emit_jsonl` CLI entry point.

    Returned for testability; `main()` calls this and then invokes
    `parse_args()`.
    """
    import argparse

    parser = argparse.ArgumentParser(
        prog="pheno-worklog-emit",
        description=(
            "Emit a JSONL audit trail from a WORKLOG.md file (ADR-032). "
            "Each line is one parsed worklog entry; the schema mirrors "
            "the markdown columns plus derived_at + tool_version."
        ),
    )
    parser.add_argument(
        "worklog",
        type=Path,
        help="Path to the source WORKLOG.md file (v1 / v2.0 / v2.1).",
    )
    parser.add_argument(
        "output",
        type=Path,
        help="Path to write the JSONL output file.",
    )
    parser.add_argument(
        "--derived-at",
        type=str,
        default=None,
        help=(
            "ISO-8601 UTC timestamp to record on every emitted line "
            "(default: current UTC time at emission). "
            "Example: 2026-06-18T12:34:56Z"
        ),
    )
    parser.add_argument(
        "--tool-version",
        type=str,
        default=None,
        help=(
            "Tool version to record on every emitted line "
            "(default: pheno_worklog_schema.__version__)."
        ),
    )
    return parser


def main(argv: Optional[list[str]] = None) -> int:
    """CLI entry point: `python3 -m pheno_worklog_schema.emit_jsonl ...`.

    Returns the process exit code (0 on success, non-zero on error).
    """
    parser = _build_arg_parser()
    args = parser.parse_args(argv)

    if not args.worklog.exists():
        print(f"error: WORKLOG not found: {args.worklog}", file=sys.stderr)
        return 2

    try:
        n = emit_jsonl(
            args.worklog,
            args.output,
            derived_at=args.derived_at,
            tool_version=args.tool_version,
        )
    except FileNotFoundError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    print(f"emitted {n} entries → {args.output}", file=sys.stdout)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())