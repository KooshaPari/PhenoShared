#!/bin/sh
# A stand-in for a real agent, used only to demonstrate that dagrun's spawn
# path, artifact contract, and verification loop actually work end to end.
#
# It reads the prompt dagrun hands it, finds every "required output" path, and
# writes a stand-in artifact that satisfies the declared predicate. A real harness
# (jcode / kcode / codex / forge) would do the actual work instead.
#
#   dagrun run --exec-template 'sh examples/fake-agent.sh {prompt}'
set -eu

prompt="${1:-}"
if [ -z "$prompt" ]; then
  echo "fake-agent: no prompt on argv" >&2
  exit 1
fi

body="$(printf '%s\n' "$prompt")"

# Extract the backticked paths from the "Required output" section.
paths="$(printf '%s\n' "$body" | sed -n 's/^- `\([^`]*\)`.*/\1/p')"
if [ -z "$paths" ]; then
  echo "fake-agent: no declared artifacts in prompt" >&2
  exit 1
fi

printf '%s\n' "$paths" | while IFS= read -r rel; do
  case "$rel" in
    *'*'*) continue ;;                 # globs are the caller's problem
  esac
  dir="$(dirname "$rel")"
  [ -d "$dir" ] || mkdir -p "$dir"
  {
    printf '# %s\n\n' "$rel"
    # Deliberately says what it is. The word "placeholder" is a marker the
    # anti-gaming check rejects, and this fixture is the one document that is
    # allowed to be honest about being synthetic without being slop.
    printf 'Generated by examples/fake-agent.sh, the offline stand-in agent.\n\n'
    printf '## Acceptance Criteria\n\n'
    i=0
    while [ "$i" -lt 40 ]; do
      printf -- '- criterion %s satisfied\n' "$i"
      i=$((i + 1))
    done
    printf '\n## Sources\n\n'
    printf -- '- https://example.invalid/source-a\n'
    printf -- '- https://example.invalid/source-b\n'
    printf '\nRequirement: the artifact exists and carries its declared shape.\n'
    printf '#### Scenario: when a node declares this artifact\n'
    printf 'then verification reads it off disk and matches its predicate.\n'
    printf '\nDecision: adopt the stand-in output for the offline demo.\n'
    printf 'Alternatives: a real harness, which needs credentials this demo does not take.\n'
    printf '\nVerdict: adopt, because every declared predicate is met.\n'
    printf '\n## Candidates\n'
    printf -- '- **Option A** — simple\n'
    printf -- '- **Option B** — complete\n'
    printf '\n## Axes\n'
    printf -- '- axis: cost vs complexity\n'
    printf -- '- axis: speed vs memory\n'
    printf -- '- axis: build size vs runtime\n'
    printf '\nStates: empty, loading, error.\n'
    printf 'Accessibility: aria labels on every control.\n'
  } > "$rel"
  echo "fake-agent: wrote $rel ($(wc -c < "$rel" | tr -d ' ') bytes)"
done
