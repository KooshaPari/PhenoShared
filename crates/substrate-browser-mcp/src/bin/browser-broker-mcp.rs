//! `browser-broker-mcp` - the browser lease broker over MCP stdio.
//!
//! Speaks JSON-RPC on stdin/stdout only. No socket is bound, so this server has
//! no network surface. Every stdout byte is protocol traffic; diagnostics go to
//! stderr.

use std::{process::ExitCode, sync::Arc};

use rmcp::{
    handler::server::{router::tool::ToolRouter, wrapper::Parameters},
    model::{
        CallToolResponse, CallToolResult, ContentBlock, Implementation, ServerCapabilities,
        ServerConfig,
    },
    tool, tool_handler, tool_router, ServerHandler, ServiceExt,
};
use serde::Serialize;

use substrate_browser_broker::BrokerError;
use substrate_browser_mcp::{
    AcquireParams, BrokerTools, PurgeParams, ReleaseParams, SharedTools, ToolError,
};

/// MCP server state: one broker tool surface, shared by all requests.
#[derive(Clone)]
pub struct BrowserBrokerMcp {
    tools: SharedTools,
    /// Tool router generated by `#[tool_router]`; read by `#[tool_handler]`.
    #[allow(dead_code)]
    tool_router: ToolRouter<Self>,
}

fn text_json<T: Serialize>(value: &T) -> CallToolResponse {
    let body = serde_json::to_string_pretty(value)
        .unwrap_or_else(|e| format!("{{\"kind\":\"Serialization\",\"message\":\"{e}\"}}"));
    CallToolResult::success(vec![ContentBlock::text(body)]).into()
}

fn tool_error(err: &BrokerError) -> CallToolResponse {
    let body = serde_json::to_string_pretty(&ToolError::from_broker(err))
        .unwrap_or_else(|e| format!("{{\"kind\":\"Serialization\",\"message\":\"{e}\"}}"));
    // Reported as tool *error* content so the agent sees the BrokerError
    // variant without the transport failing.
    CallToolResult::error(vec![ContentBlock::text(body)]).into()
}

#[tool_router]
impl BrowserBrokerMcp {
    /// Build the server around an already-opened tool surface.
    #[must_use]
    pub fn new(tools: Arc<BrokerTools>) -> Self {
        Self {
            tools,
            tool_router: Self::tool_router(),
        }
    }

    /// Read-only broker snapshot.
    #[tool(
        name = "broker_status",
        description = "Read-only snapshot of the browser lease broker: state root, whether a \
                       Chrome-family browser is available to launch, how many live sessions this \
                       process holds, and every lease record on disk (expired ones flagged)."
    )]
    async fn broker_status(&self) -> Result<CallToolResponse, rmcp::ErrorData> {
        match self.tools.status().await {
            Ok(status) => Ok(text_json(&status)),
            Err(err) => Ok(tool_error(&err)),
        }
    }

    /// Acquire an exclusive browser profile and hold it under a lease.
    #[tool(
        name = "broker_acquire",
        description = "Acquire an exclusive lease on a browser profile. The browser is launched \
                       on that profile's first action, not here, so the grant returns immediately \
                       and no browser process is started by this call. \
                       Returns the lease id and the fencing token that every later mutation must \
                       present. One holder per principal/profile. On failure the broker's own \
                       error variant is returned (ProfileBusy, Browser, Refused, ...)."
    )]
    async fn broker_acquire(
        &self,
        Parameters(params): Parameters<AcquireParams>,
    ) -> Result<CallToolResponse, rmcp::ErrorData> {
        match self.tools.acquire(params).await {
            Ok(info) => Ok(text_json(&info)),
            Err(err) => Ok(tool_error(&err)),
        }
    }

    /// Release a lease, fail-closed on a stale fencing token.
    #[tool(
        name = "broker_release",
        description = "Release a leased browser profile. The fencing token is validated by the \
                       broker's on-disk lease store FIRST: a stale, expired, revoked or \
                       superseded token is refused and nothing is torn down. On success the \
                       browser is closed, the lease revoked and the generation sealed."
    )]
    async fn broker_release(
        &self,
        Parameters(params): Parameters<ReleaseParams>,
    ) -> Result<CallToolResponse, rmcp::ErrorData> {
        match self
            .tools
            .release(&params.lease_id, params.fencing_token)
            .await
        {
            Ok(outcome) => Ok(text_json(&outcome)),
            Err(err) => Ok(tool_error(&err)),
        }
    }

    /// List live sessions.
    #[tool(
        name = "broker_live",
        description = "List the live browser sessions this process holds, after reaping any whose \
                       lease expired, was revoked or was superseded. A listing is a hint: every \
                       mutating action re-validates the lease."
    )]
    async fn broker_live(&self) -> Result<CallToolResponse, rmcp::ErrorData> {
        Ok(text_json(&self.tools.live().await))
    }

    /// Reap stale sessions.
    #[tool(
        name = "broker_reap",
        description = "Reap sessions whose lease no longer validates (expired, revoked, superseded) \
                       and leases whose owning process is gone. Returns how many sessions were \
                       reaped and how many live sessions remain."
    )]
    async fn broker_reap(&self) -> Result<CallToolResponse, rmcp::ErrorData> {
        match self.tools.reap().await {
            Ok(outcome) => Ok(text_json(&outcome)),
            Err(err) => Ok(tool_error(&err)),
        }
    }

    /// Delete a profile's data directory (destructive).
    #[tool(
        name = "broker_purge",
        description = "DESTRUCTIVE: delete every generation of a browser profile. Requires \
                       confirm: true. Refused while the profile has a live session or any \
                       unexpired lease on disk, so a purge can never race a live holder."
    )]
    async fn broker_purge(
        &self,
        Parameters(params): Parameters<PurgeParams>,
    ) -> Result<CallToolResponse, rmcp::ErrorData> {
        match self
            .tools
            .purge(&params.principal, &params.profile, params.confirm)
            .await
        {
            Ok(outcome) => Ok(text_json(&outcome)),
            Err(err) => Ok(tool_error(&err)),
        }
    }
}

// rmcp's `#[tool_handler]` expansion emits async entry points that may not
// contain an await; the lint fires inside the macro with no local span.
#[allow(clippy::unused_async_trait_impl)]
#[tool_handler]
impl ServerHandler for BrowserBrokerMcp {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::default())
            .with_server_info(Implementation::new(
                "browser-broker-mcp",
                env!("CARGO_PKG_VERSION"),
            ))
            .with_instructions(
                "The browser lease broker, over stdio. Leases are the only authority: acquire a \
                 profile with broker_acquire, keep the fencing token, and present it on \
                 broker_release. A stale token is refused, never silently accepted. Purge is \
                 destructive and needs confirm: true.",
            )
    }
}

#[tokio::main]
async fn main() -> ExitCode {
    // stderr only: stdout is the JSON-RPC pipe.
    let tools = match BrokerTools::open_default() {
        Ok(tools) => tools,
        Err(err) => {
            eprintln!("browser-broker-mcp: cannot open broker state: {err}");
            return ExitCode::FAILURE;
        },
    };
    eprintln!("browser-broker-mcp: authority {}", tools.authority());

    let server = BrowserBrokerMcp::new(Arc::new(tools));
    let transport = rmcp::transport::io::stdio();

    match server.serve(transport).await {
        Ok(service) => match service.waiting().await {
            Ok(_) => ExitCode::SUCCESS,
            Err(err) => {
                eprintln!("browser-broker-mcp: serve failed: {err}");
                ExitCode::FAILURE
            },
        },
        Err(err) => {
            eprintln!("browser-broker-mcp: handshake failed: {err}");
            ExitCode::FAILURE
        },
    }
}
