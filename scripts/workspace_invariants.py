#!/usr/bin/env python3
"""Guard the monorepo's Cargo workspace topology.

Every Cargo.toml that declares a [package] must belong to exactly one workspace:
either the root workspace, a nested workspace, or an explicitly allowlisted
legacy tree (attic/archives/absorption/...). Anything else is unowned code that
`cargo metadata`, `cargo audit` and `cargo machete` silently skip.

The checked-in baseline suppresses existing violations so the gate can be
enabled immediately. New violations fail CI. Shrink the baseline as crates are
adopted or archived.

Usage:
    python3 scripts/workspace_invariants.py            # check against baseline
    python3 scripts/workspace_invariants.py --summary  # counts only
    python3 scripts/workspace_invariants.py --write-baseline
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

SKIP_DIRS = {
    ".git",
    ".hg",
    ".svn",
    "target",
    "node_modules",
    ".venv",
    "venv",
    "dist",
    "build",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
}

# Trees that are explicitly legacy, vendored or absorbed wholesale. They are
# allowed to contain manifests that no workspace owns. Keep this list short and
# delete entries as the trees are pruned.
ALLOW_PREFIXES = (
    "attic/",
    "archives/",
    "_archived/",
    "absorption/",
    "audits/",
    "registry/absorbed-crates/",
    "templates/",
    "third_party/",
    "vendor/",
    ".vendor/",
)

BASELINE = Path(__file__).with_name("workspace_invariants_baseline.txt")


def manifests(root: Path):
    for path in root.rglob("Cargo.toml"):
        if any(part in SKIP_DIRS for part in path.parts):
            continue
        yield path


def load(path: Path) -> dict:
    try:
        return tomllib.loads(path.read_text(encoding="utf-8", errors="replace"))
    except (tomllib.TOMLDecodeError, OSError):
        return {}


def expand(root: Path, pattern: str) -> list[Path]:
    if any(ch in pattern for ch in "*?["):
        return [p for p in root.glob(pattern) if p.is_dir()]
    return [root / pattern]


def workspace_of(path: Path) -> dict | None:
    data = load(path)
    ws = data.get("workspace")
    if not isinstance(ws, dict):
        return None
    return ws


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=Path(__file__).resolve().parents[1])
    parser.add_argument("--baseline", default=BASELINE)
    parser.add_argument("--write-baseline", action="store_true")
    parser.add_argument("--summary", action="store_true")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    baseline_path = Path(args.baseline)

    all_manifests = sorted(manifests(root))
    packages: dict[Path, str] = {}
    workspaces: list[Path] = []
    owned: set[Path] = set()
    excluded: set[Path] = set()

    for manifest in all_manifests:
        data = load(manifest)
        if isinstance(data.get("package"), dict):
            packages[manifest.parent.resolve()] = data["package"].get("name", "?")
        ws = data.get("workspace")
        if isinstance(ws, dict):
            workspaces.append(manifest.parent.resolve())

    for ws_root in workspaces:
        ws = workspace_of(ws_root / "Cargo.toml") or {}
        for pattern in ws.get("members", []):
            for member in expand(ws_root, pattern):
                owned.add(member.resolve())
        for pattern in ws.get("exclude", []):
            for item in expand(ws_root, pattern):
                excluded.add(item.resolve())

    def allowed(rel: str) -> bool:
        return any(rel.startswith(prefix) for prefix in ALLOW_PREFIXES)

    violations: list[str] = []
    allowlisted = 0
    for pkg_dir in packages:
        if pkg_dir in owned or pkg_dir in excluded:
            continue
        rel = pkg_dir.relative_to(root).as_posix()
        if allowed(rel + "/"):
            allowlisted += 1
            continue
        violations.append(rel)

    violations.sort()
    baseline = []
    if baseline_path.exists():
        baseline = [
            line.strip()
            for line in baseline_path.read_text(encoding="utf-8").splitlines()
            if line.strip() and not line.startswith("#")
        ]
    known = set(baseline)
    current = set(violations)
    new = sorted(current - known)
    fixed = sorted(known - current)

    if args.write_baseline:
        baseline_path.write_text(
            "# Manifests not owned by any Cargo workspace.\n"
            "# Generated by scripts/workspace_invariants.py --write-baseline.\n"
            "# Remove entries as crates are adopted or archived; never add inventively.\n"
            + "".join(line + "\n" for line in violations),
            encoding="utf-8",
        )
        print(f"wrote {len(violations)} baseline entries to {baseline_path}")
        return 0

    print(
        f"manifests={len(all_manifests)} packages={len(packages)} "
        f"workspaces={len(workspaces)} owned={len(owned)} excluded={len(excluded)} "
        f"allowlisted={allowlisted} violations={len(violations)} "
        f"baseline={len(baseline)} new={len(new)} fixed={len(fixed)}"
    )
    if args.summary:
        for rel in violations:
            print(f"  unowned: {rel}")
        return 0

    if fixed:
        print(
            f"note: {len(fixed)} baseline entries no longer violate; "
            "run --write-baseline to shrink the baseline:",
            file=sys.stderr,
        )
        for rel in fixed[:10]:
            print(f"  fixed: {rel}", file=sys.stderr)

    if new:
        print("error: manifests are not owned by any workspace and are not allowlisted:", file=sys.stderr)
        for rel in new:
            print(f"::error file={rel}/Cargo.toml::not a member of any Cargo workspace", file=sys.stderr)
            print(f"  {rel}", file=sys.stderr)
        print(
            "Add the crate to Cargo.toml members, move it under an allowlisted tree, "
            "or give it its own [workspace] table.",
            file=sys.stderr,
        )
        return 1

    print("ok: no new unowned manifests")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
